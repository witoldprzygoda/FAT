#!/usr/bin/env python3
# x17ab_tex.py -- LaTeX snippets of the x17ab package from its text tables (docs/latex/tables_all/x17ab_{toys,nuis,toycls}.txt)
# run: python3 plots/all_report/x17ab_tex.py   (from /home/przygoda/HADES/FAT/FAT)
import re, os
T = '/home/przygoda/HADES/FAT/FAT/docs/latex/tables_all'
# ---- toys
txt = open(f'{T}/x17ab_toys.txt').read()
rows = {}
for b in re.split(r'\n## cfg ', txt)[1:]:
    head, rest = b.split('\n', 1)
    cfg = int(head.split(':')[0]); desc = head.split(':', 1)[1].strip()
    vals = [l.split() for l in rest.split('\n') if re.match(r'^\s*\d+\s+\d+', l)]
    lin = [l for l in rest.split('\n') if l.startswith('linearity')][0]
    m = re.search(r'BR1: slope ([\d.]+) \+- ([\d.]+), offset ([+-][\d.]+) e-6;  BR2: slope ([\d.]+) \+- ([\d.]+), offset ([+-][\d.]+)', lin)
    rows[cfg] = dict(desc=desc, s1=float(m.group(1)), s1e=float(m.group(2)), s2=float(m.group(4)), s2e=float(m.group(5)), o2=m.group(6),
                     cov=[v[10] for v in vals], cov2c=[v[13] for v in vals], chi=vals[0][18])
def tx(d): return d.replace('%', r'\%').replace('_', r'\_').replace('^2', r'$^2$')
out = [r"% x17ab_toys.tex -- generated by x17ab_tex.py from x17ab_toys.txt (x17ab_summary.C); WP9 X-b",
       r"\begin{tabular}{rlccrcccr}", r"\toprule",
       r"cfg & toys and fit & slope (1) & slope (2) & offset (2) & cov.\ $10^{-5}$ & cov.\ $3{\times}10^{-5}$ & cov.\ (2) corr. & $\tilde{\chi}^2$ \\",
       r" & & $r\times2.68{\times}10^{-4}$ & $N_X/s_1$ & [$10^{-6}$] & UL $\ge$ BR & UL $\ge$ BR & $10^{-5}$ / $3{\times}10^{-5}$ & /ndf \\", r"\midrule"]
for c in [0, 1, 2, 7, 6, 18, 4, 10, 11, 14, 13, 15, 16, 17, 12]:
    if c not in rows: continue
    r = rows[c]
    out.append(f"{c} & {tx(r['desc'])} & {r['s1']:.3f}({round(r['s1e']*1e3)}) & {r['s2']:.3f}({round(r['s2e']*1e3)}) & {r['o2']} & "
               f"{r['cov'][3]} & {r['cov'][4]} & {r['cov2c'][3]} / {r['cov2c'][4]} & {r['chi']} \\\\")
    if c == 4: out.append(r"\midrule")
out += [r"\bottomrule", r"\end{tabular}"]
open(f'{T}/x17ab_toys.tex', 'w').write('\n'.join(out) + '\n')
# ---- nuisances
out = [r"% x17ab_nuis.tex -- generated by x17ab_tex.py from x17ab_nuis.txt (x17ab_model.C); pre-data projection, simulation Asimov set",
       r"\begin{tabular}{llrrr}", r"\toprule", r"variant & description & $\hat r\times2.68{\times}10^{-4}$ & UL [$10^{-6}$] & UL/UL$_0$ \\", r"\midrule"]
start = False
for l in open(f'{T}/x17ab_nuis.txt'):
    if l.startswith('variant'): start = True; continue
    if not start or not l.strip() or l.startswith('C4 replicas') or l.startswith('N5 over'): continue
    a = l.split()
    ul = '--' if a[3] == 'nan' else f"{float(a[3])*1e6:.1f}"
    rat = '--' if a[4] == 'nan' else a[4]
    out.append(f"{tx(a[0])} & {tx(' '.join(a[6:]))} & {float(a[1])*1e6:+.2f}$\\times10^{{-6}}$ & {ul} & {rat} \\\\")
out += [r"\bottomrule", r"\end{tabular}"]
open(f'{T}/x17ab_nuis.tex', 'w').write('\n'.join(out) + '\n')
# ---- toy CLs
out = [r"% x17ab_toycls.tex -- generated by x17ab_tex.py from x17ab_toycls.txt (x17ab_toycls.C, x17ab_clsfig.C)",
       r"\begin{tabular}{rlrrr}", r"\toprule", r"set & data set & UL asympt.\ [$10^{-6}$] & UL toys [$10^{-6}$] & ratio \\", r"\midrule"]
for l in open(f'{T}/x17ab_toycls.txt'):
    m = re.match(r'^(\d)\s+(.*?)\s{2,}([\d.e+-]+)\s+([\d.e+-]+|-)\s+([\d.]+|-)', l)
    if not m: continue
    d = tx(m.group(2)).replace('e+00', '').replace('1e-05', r'$10^{-5}$')
    t = '--' if m.group(4) == '-' else f"{float(m.group(4))*1e6:.2f}"
    out.append(f"{m.group(1)} & {d} & {float(m.group(3))*1e6:.2f} & {t} & {m.group(5).replace('-', '--')} \\\\")
out += [r"\bottomrule", r"\end{tabular}"]
open(f'{T}/x17ab_toycls.tex', 'w').write('\n'.join(out) + '\n')
print('x17ab_tex: written x17ab_toys.tex, x17ab_nuis.tex, x17ab_toycls.tex')
